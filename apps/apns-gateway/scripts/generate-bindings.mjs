#!/usr/bin/env node
// Why: Wrangler marks its binding file as generated so the formatter skips it; temporarily replace
// that marker so the checked-in binding remains stable under the repository's canonical formatter.
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const PACKAGE_ROOT = join(import.meta.dirname, '..')
const bindingsPath = join(PACKAGE_ROOT, 'worker-configuration.d.ts')
const result = spawnSync('wrangler', ['types'], { cwd: PACKAGE_ROOT, stdio: 'inherit' })

if (result.error) {
  throw result.error
}
if (result.status !== 0) {
  process.exitCode = result.status ?? 1
} else {
  const bindings = readFileSync(bindingsPath, 'utf8')
  const generatedMarker = '// Generated by Wrangler'
  const formatMarker = '// Wrangler binding source'
  const formatResult = spawnSync(
    'vp',
    ['fmt', '--stdin-filepath', join(PACKAGE_ROOT, 'src', 'worker-bindings.ts')],
    {
      cwd: PACKAGE_ROOT,
      encoding: 'utf8',
      input: bindings.replace(generatedMarker, formatMarker),
      stdio: ['pipe', 'pipe', 'inherit']
    }
  )
  if (formatResult.error) {
    throw formatResult.error
  }
  if (formatResult.status !== 0) {
    process.exitCode = formatResult.status ?? 1
  } else {
    writeFileSync(bindingsPath, formatResult.stdout.replace(formatMarker, generatedMarker))
  }
}
