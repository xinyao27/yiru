export const IconContext = createContext<PhosphorIconProps>({ weight: 'regular' })

// Why: Phosphor does not expose native className props, so this module keeps
// icon colors on Uniwind's token path and gives every mobile icon one default weight.
function withMobileIcon(Icon: PhosphorIcon) {
  function MobileIcon(props: PhosphorIconProps) {
    const context = useContext(IconContext)
    return createElement(Icon, {
      ...context,
      ...props,
      weight: props.weight ?? context.weight ?? 'regular'
    })
  }
  return withUniwind(MobileIcon)
}

